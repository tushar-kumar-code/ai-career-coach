export function getLocalizedQuestion(question: Question | undefined, lang: Language): Question | undefined {
  if (!question) return undefined;
  if (lang !== 'hi') return question;

  const orderIndex = question.order_index;
  const hiData = HINDI_QUESTION_MAP[orderIndex];

  if (!hiData) return question;

  const localizedOptions = question.options.map((opt) => ({
    ...opt,
    text: hiData.options[opt.id] || opt.text,
  }));

  return {
    ...question,
    dimension: hiData.dimension,
    question_text: hiData.question_text,
    options: localizedOptions,
  };
}
