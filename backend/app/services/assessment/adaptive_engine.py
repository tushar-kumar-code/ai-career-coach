class AdaptiveAssessmentEngine:
    """
    Intelligent Adaptive Career Discovery Assessment Engine.
    
    RULES:
    1. MINIMUM 10 QUESTIONS:
       Every candidate MUST be asked at least 10 questions so that their analysis is thorough,
       multi-dimensional, and reliable.
    2. GROQ AI DECISION AFTER 10 QUESTIONS:
       After 10 questions have been answered, Groq AI evaluates the candidate's answers and decides
       whether sufficient clarity has been reached (conclude quiz) or if more questions are needed.
    3. ADAPTIVE GENERATION:
       Each question is dynamically generated by Groq AI based on deep analysis of all previous
       questions and candidate's chosen answers.
    """

    MIN_QUESTIONS: int = 10
    MAX_SAFETY_QUESTIONS: int = 18
    MAX_QUESTIONS_PER_SESSION: int = 18

    async def get_next_question(
        self,
        db: AsyncSession,
        answered_question_ids: List[str],
        current_answers: Dict[str, Any],
        language: str = "en",
        ai_provider: Optional[BaseLLMProvider] = None,
        user_level: str = "beginner",
        excluded_question_ids: Optional[Set[str]] = None,
        past_questions_summary: Optional[List[str]] = None,
        is_retake: bool = False,
        attempt_num: int = 1
    ) -> Optional[Question]:
        step_num = len(answered_question_ids) + 1

        # Safety ceiling: If max safety questions reached, stop questions and proceed to final analysis
        if step_num > self.MAX_SAFETY_QUESTIONS:
            logger.info(f"🛑 [GROQ ASSESSMENT] Max safety ceiling ({self.MAX_SAFETY_QUESTIONS}) reached. Concluding assessment.")
            return None

        # Always ensure Groq AI provider is used for assessment intelligence
        from app.services.ai.client import AIService
        if not ai_provider or getattr(ai_provider, "__class__", None).__name__ != "GroqProvider":
            ai_provider = AIService.get_provider("groq")

        # -------------------------------------------------------------------
        # DECISION LOGIC:
        # If user has answered at least MIN_QUESTIONS (10 questions answered, step_num > 10):
        # Groq AI checks if it has sufficient clarity to predict the career domain.
        # -------------------------------------------------------------------
        if step_num > self.MIN_QUESTIONS and ai_provider:
            logger.info(
                f"🔍 [GROQ CLARITY CHECK] Candidate has completed {len(current_answers)} questions (Mandatory {self.MIN_QUESTIONS} met). "
                f"Groq AI is evaluating if candidate analysis is complete or more questions are needed..."
            )
            try:
                evaluation = await self._evaluate_clarity_with_ai(
                    current_answers=current_answers,
                    user_level=user_level,
                    language=language,
                    ai_provider=ai_provider,
                    step_num=step_num
                )
                if evaluation and evaluation.has_sufficient_clarity and (evaluation.confidence_score or 0) >= 75:
                    logger.info(
                        f"🎯 [GROQ CLARITY ACHIEVED] Groq AI successfully predicted career domain '{evaluation.predicted_domain}' "
                        f"with confidence {evaluation.confidence_score}% after {len(current_answers)} questions. Concluding quiz for final report."
                    )
                    return None
                else:
                    logger.info(
                        f"➕ [GROQ EXTENDING ASSESSMENT] Candidate interests require deeper analysis after {len(current_answers)} questions. "
                        f"Groq AI is adding Question #{step_num} adaptively!"
                    )
                    if evaluation and evaluation.next_question and len(evaluation.next_question.options) >= 4:
                        return await self._save_generated_question(db, evaluation.next_question, step_num)
            except Exception as eval_err:
                logger.warning(f"⚠️ [GROQ CLARITY CHECK NOTICE] {eval_err}. Generating next adaptive question.")

        # -------------------------------------------------------------------
        # If step_num <= MIN_QUESTIONS (Questions 1 through 10) OR if Groq needed more questions:
        # Dynamically generate Question #{step_num} via Groq AI based on previous answer analysis!
        # -------------------------------------------------------------------
        if ai_provider:
            logger.info(
                f"🧠 [GROQ ASSESSMENT] Generating Question #{step_num} (Min {self.MIN_QUESTIONS} required) "
                f"based on analysis of previous {len(current_answers)} answer(s)..."
            )
            try:
                ai_q = await self._generate_ai_adaptive_question(
                    db=db,
                    step_num=step_num,
                    answered_question_ids=answered_question_ids,
                    current_answers=current_answers,
                    language=language,
                    ai_provider=ai_provider,
                    user_level=user_level,
                    past_questions_summary=past_questions_summary,
                    is_retake=is_retake,
                    attempt_num=attempt_num
                )
                if ai_q:
                    logger.info(f"✨ [GROQ QUESTION READY] Question #{step_num} loaded: \"{ai_q.question_text[:70]}...\"")
                    return ai_q
            except Exception as e:
                logger.warning(f"⚠️ [GROQ QUESTION GENERATION RETRY] {str(e)}. Using adaptive fallback.")

        # In-memory adaptive fallback
        return await self._generate_simple_adaptive_fallback(
            db=db,
            step_num=step_num,
            current_answers=current_answers,
            language=language
        )

    async def _evaluate_clarity_with_ai(
        self,
        current_answers: Dict[str, Any],
        user_level: str,
        language: str,
        ai_provider: BaseLLMProvider,
        step_num: int
    ) -> Optional[AdaptiveEvaluationResponse]:
        """Asks Groq AI to check whether enough clarity has been attained after at least 10 questions."""
        history_lines = []
        for idx, (q_id, ans) in enumerate(current_answers.items(), 1):
            dim = ans.get("dimension", "General")
            txt = ans.get("option_text", "")
            arch = ans.get("archetype", "")
            arch_note = f" (Indicates: {arch})" if arch else ""
            history_lines.append(f"Q#{idx} [{dim}]: Selected '{txt}'{arch_note}")

        history_text = "\n".join(history_lines)

        lang_rule = "Write any next_question and options in simple, everyday English."
        if language == "hi":
            lang_rule = "Write any next_question and options in simple, natural Hindi."

        prompt = f"""
You are an expert AI Career Discovery Coach powered by Groq.
The candidate has completed {len(current_answers)} questions (satisfying the minimum 10 questions requirement).

CANDIDATE ANSWERS HISTORY ({len(current_answers)} QUESTIONS):
{history_text}

CANDIDATE LEVEL: {user_level}

YOUR DECISION TASK:
1. Analyze the complete pattern of answers across all {len(current_answers)} questions.
2. Determine: Do you now have sufficient clarity and high confidence (>=80%) to definitively identify their best-fit tech career domain (e.g. Frontend Engineering, UI/UX Design, Backend/Systems, Data Science & AI, Cloud/DevOps, or Product Strategy)?
   - If YES (the signals are consistent, distinct, and sufficient):
     Set `has_sufficient_clarity = true`
     Provide `predicted_domain`
     Provide `confidence_score` (between 80 and 100)
     Set `next_question = null`
   - If NO (their interests are still split between two domains, ambiguous, or require further confirmation):
     Set `has_sufficient_clarity = false`
     Generate an EXTREMELY EASY, engaging Question #{step_num} with 4 options (A, B, C, D) specifically designed to resolve the ambiguity between their top competing interests based on their prior choices.

{lang_rule}
"""
        return await ai_provider.generate_structured(
            prompt=prompt,
            output_schema=AdaptiveEvaluationResponse,
            system_instruction="You are an expert AI Career Coach evaluating candidate mindset and deciding whether further questions are needed."
        )

    async def _save_generated_question(self, db: AsyncSession, gen_q: GeneratedQuestion, step_num: int) -> Question:
        formatted_options = [
            {
                "id": opt.id,
                "text": opt.text,
                "archetype": opt.archetype,
                "weights": {opt.target_role: 9, opt.archetype: 8}
            }
            for opt in gen_q.options
        ]
        new_q = Question(
            id=str(uuid.uuid4()),
            dimension=gen_q.dimension,
            question_type="adaptive_ai",
            question_text=gen_q.question_text,
            options=formatted_options,
            difficulty_level=1,
            order_index=step_num
        )
        db.add(new_q)
        await db.commit()
        await db.refresh(new_q)
        return new_q

