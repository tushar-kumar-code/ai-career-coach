logger = logging.getLogger(__name__)


class GeneratedOption(BaseModel):
    id: str = Field(description="Option ID: A, B, C, or D")
    text: str = Field(description="Clear, easy-to-understand option text in plain simple language")
    archetype: str = Field(description="Archetype: Systems Builder, Data Investigator, Creative Visualizer, Cloud Architect, User Strategist, AI Pioneer")
    target_role: str = Field(description="Target role associated with option, e.g. Frontend Developer, Backend Developer, Data Scientist, Product Manager")


class GeneratedQuestion(BaseModel):
    dimension: str = Field(description="Dimension or topic area for this question")
    question_text: str = Field(description="Very easy, clear, relatable question written in everyday language. No jargon. Any student can read and answer this.")
    options: List[GeneratedOption] = Field(description="Array of 4 options A, B, C, D")


class AdaptiveEvaluationResponse(BaseModel):
    has_sufficient_clarity: bool = Field(
        description="Set to True ONLY if you have enough clear signals and high confidence (>=80%) to accurately predict the user's best career domain. Set to False if their interests are split, mixed, or need further probing."
    )
    predicted_domain: Optional[str] = Field(
        default=None,
        description="The predicted best-fit domain if has_sufficient_clarity is True (e.g. Frontend Engineering, UI/UX Design, Backend Systems, Data Science & AI, Product Management, Cloud & DevOps)"
    )
    confidence_score: Optional[int] = Field(
        default=None,
        description="Confidence percentage (0-100) in your prediction"
    )
    next_question: Optional[GeneratedQuestion] = Field(
        default=None,
        description="The next targeted question to ask if has_sufficient_clarity is False. Must provide 4 simple, easy options A, B, C, D."
    )


